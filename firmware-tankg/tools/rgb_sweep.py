#!/usr/bin/env python3
"""Calibrate and map the 12 RGB footswitch pixels over USB CDC (commands RGB / RGBOFF / RGBDIV / RGBPAT of firmware-tankg). UNTESTED ON HARDWARE.
  ~/.local/share/pipx/venvs/platformio/bin/python tools/rgb_sweep.py [--port /dev/ttyACM0] [--skip-calib] [--level 10]
Phase 1  calibration: tries SPI divider / bit-pattern combinations, each time lighting ALL pixels pure red at low level. Answer 'r' when ALL pixels are the
         same pure red; or describe what you see (free text, e.g. '1 verde 3 laranja'); 's' skips the rest of the phase; 'q' quits.
Phase 2  mapping: lights ONE pixel (0..11) red at a time. Answer 'fs<1-4> <pos>' e.g. 'fs2 b' (pos = a/b/c within that footswitch's ring, any labels you like),
         'n' = nothing, or free text. A single lit pixel also reveals data shifts (a wrong pixel/colour for pixel N means the stream is misaligned).
Phase 3  channel order: pixel 0 is sent pure green then pure blue; type the colour you see (r/g/b/n/free).
Results are saved after each answer to build/rgb_sweep.json; at the end src/rgb_map.h can be written (confirmation asked). Resume = same command."""
import argparse, json, os, re, sys, time
try: import serial
except ImportError: sys.exit('pyserial missing -> run with ~/.local/share/pipx/venvs/platformio/bin/python')
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JSON = os.path.join(HERE, 'build', 'rgb_sweep.json'); HDR = os.path.join(HERE, 'src', 'rgb_map.h')
CAND = [(9, '7e', '60')] + [(d, '7e', '60') for d in (8, 10, 7, 11, 6, 12, 5, 14, 4, 18, 3, 24, 2, 36)] + [(9, 'f8', 'c0'), (9, 'fc', 'c0'), (9, 'f0', 'c0'), (9, '7c', '60'), (9, 'f8', 'e0'), (9, '78', '60')]

class Dev:
    def __init__(self, port):
        self.s = serial.Serial(port, 115200, timeout=0.3)
        try: self.s.dtr = True
        except OSError: pass
        time.sleep(0.3); self.s.reset_input_buffer()
    def cmd(self, line, t=2.0):
        self.s.write((line + '\n').encode()); end = time.time() + t; last = ''
        while time.time() < end:
            r = self.s.readline().decode(errors='replace').strip()
            if r:
                last = r
                if r.startswith(('OK', 'ERR', 'PONG')): return r
        return last

def load():
    try: return json.load(open(JSON))
    except Exception: return {'calib': [], 'good': None, 'pixels': {}, 'order': {}}
def save(d):
    os.makedirs(os.path.dirname(JSON), exist_ok=True); json.dump(d, open(JSON, 'w'), indent=1, ensure_ascii=False)

def parse_px(a):
    a = re.sub(r'\s+', ' ', a.strip().lower())
    m = re.fullmatch(r'fs ?([1-4]) ?([a-z0-9]*)', a)
    return {'fs': int(m.group(1)) - 1, 'pos': m.group(2)} if m else {'fs': None}

def write_header(d):
    tab = [[-1] * 3 for _ in range(4)]; names = [[''] * 3 for _ in range(4)]; conf = []
    for k, v in sorted(d['pixels'].items(), key=lambda x: int(x[0])):
        p = v['parsed']
        if p.get('fs') is None: continue
        pos = p['pos']; idx = ('abc'.find(pos) if pos in ('a', 'b', 'c') else ('123'.find(pos) if pos in ('1', '2', '3') else -1))
        if idx < 0: conf.append(f'pixel {k}: position "{pos}" is not a/b/c/1/2/3, skipped'); continue
        if tab[p['fs']][idx] != -1: conf.append(f'fs{p["fs"]+1}/{pos} already pixel {tab[p["fs"]][idx]}, also {k}')
        tab[p['fs']][idx] = int(k)
    od = d['order']
    lines = ['// GENERATED by tools/rgb_sweep.py -- observed by a human on the real pedal; -1 = not observed. UNTESTED beyond that sweep.',
             '#pragma once', '#include <stdint.h>', 'namespace tg {',
             f'// good SPI settings found in calibration: {json.dumps(d["good"])}',
             '// pixel index (0..11, as sent by the RGB command) for [footswitch 0..3][position a,b,c]',
             'constexpr int8_t kRgbPixel[4][3] = {' + ', '.join('{' + ','.join(map(str, r)) + '}' for r in tab) + '};',
             f'// colour seen when pixel 0 was sent pure green / pure blue: {json.dumps(od, ensure_ascii=False)}', '}  // namespace tg', '']
    open(HDR, 'w').write('\n'.join(lines)); print(f'\nWrote {HDR}')
    for c in conf: print('  WARNING:', c)

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--port', default='/dev/ttyACM0'); ap.add_argument('--skip-calib', action='store_true'); ap.add_argument('--fresh', action='store_true')
    ap.add_argument('--level', type=int, default=16, help='brightness 1..255 of the lit channel (default 16)')
    ap.add_argument('--header', default=HDR); ap.add_argument('--json', default=JSON)
    a = ap.parse_args(); globals()['HDR'], globals()['JSON'] = a.header, a.json
    lv = max(1, min(255, a.level)); hx = f'{lv:02x}'
    try: dev = Dev(a.port)
    except Exception as e: sys.exit(f'cannot open {a.port}: {e}')
    r = dev.cmd('PING')
    if 'PONG' not in r and not r.startswith('OK'): sys.exit('no reply from the pedal firmware: ' + r)
    d = {'calib': [], 'good': None, 'pixels': {}, 'order': {}} if a.fresh else load()
    if not a.skip_calib and d['good'] is None:
        print('\n=== Fase 1: calibração (todos os pixels em vermelho fraco) ===')
        for div, one, zero in CAND:
            print('  ', dev.cmd(f'RGBPAT {one} {zero}'), '|', dev.cmd(f'RGBDIV {div}'), '|', dev.cmd('RGBOFF'), '|', dev.cmd(f'RGB ALL {hx}0000'))
            ans = input(f'  div={div} pat={one}/{zero}: todos iguais e VERMELHO puro? [r = sim / texto = o que vê / s = pular fase / q] ').strip()
            if ans.lower() == 'q': save(d); return 0
            if ans.lower() == 's': break
            d['calib'].append({'div': div, 'one': one, 'zero': zero, 'answer': ans}); save(d)
            if ans.lower() == 'r': d['good'] = {'div': div, 'one': one, 'zero': zero}; save(d); print('  -> calibração ok'); break
        else: print('Nenhuma combinação deu vermelho puro; seguindo com a última (a varredura de pixel única ainda ajuda a diagnosticar).')
    elif d['good']: g = d['good']; dev.cmd(f'RGBPAT {g["one"]} {g["zero"]}'); dev.cmd(f'RGBDIV {g["div"]}'); print('Usando calibração salva:', g)
    print('\n=== Fase 2: um pixel por vez ===')
    todo = [i for i in range(12) if str(i) not in d['pixels']]
    for i in todo:
        dev.cmd('RGBOFF'); resp = dev.cmd(f'RGB {i} {hx}0000')
        ans = input(f'[pixel {i:2d}/11] {resp}\n   qual footswitch e posição acendeu? (ex: fs2 b | n = nada | q) ').strip()
        if ans.lower() == 'q': break
        d['pixels'][str(i)] = {'answer': ans, 'parsed': parse_px(ans)}; save(d)
    dev.cmd('RGBOFF')
    if not d['order'] and len(d['pixels']) == 12:
        print('\n=== Fase 3: ordem dos canais (pixel 0) ===')
        for name, val in (('green', f'00{hx}00'), ('blue', f'0000{hx}')):
            dev.cmd('RGBOFF'); dev.cmd(f'RGB 0 {val}'); d['order'][name] = input(f'  pixel 0 enviado como {name.upper()} puro: que cor aparece? ').strip(); save(d)
        dev.cmd('RGBOFF')
    print('\n--- resumo ---'); print(json.dumps({k: v for k, v in d.items() if k != 'calib'}, indent=1, ensure_ascii=False)[:1500])
    if input('\nGravar src/rgb_map.h? [s/N] ').strip().lower() in ('s', 'sim', 'y'): write_header(d)
    return 0
if __name__ == '__main__': sys.exit(main())
