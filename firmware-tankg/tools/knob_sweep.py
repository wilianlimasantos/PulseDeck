#!/usr/bin/env python3
"""Map the 15 front-panel knobs to the 16 raw slots of the firmware's KNOBS command. UNTESTED ON HARDWARE.
  ~/.local/share/pipx/venvs/platformio/bin/python tools/knob_sweep.py [--port /dev/ttyACM0] [--threshold 200] [--ch 8] [--resume]
Run it in a REAL terminal. Needs pyserial (the PlatformIO venv has it). Close PulseDeck first (it owns the port).
1. Captures a baseline (median of several KNOBS reads, 16 slots).
2. For each knob, MASTER -> NOISE GATE (left to right as the LEDs are numbered), it asks you to turn THAT knob a good way and keeps polling; the slot whose
   value moves more than --threshold (default 200 of 1023) away from the baseline is taken as that knob's slot. Slots already assigned are ignored.
   When one is found it waits until the readings are still again, takes a new baseline and moves to the next knob.
Keys (type then Enter, any time while it polls):  s skip this knob   b go back one knob (forget its slot)   r re-take the baseline   q save and quit
Writes build/knob_sweep.json after every knob and, at the end (also on q), src/knob_map.h. Slot 15 is suspected to be a voltage sensor, not a knob."""
import argparse, json, os, re, select, statistics, sys, time, datetime
try:
    import serial
except ImportError:
    sys.exit('pyserial missing -> run with ~/.local/share/pipx/venvs/platformio/bin/python')
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JSON = os.path.join(HERE, 'build', 'knob_sweep.json'); HDR = os.path.join(HERE, 'src', 'knob_map.h')
KNOBS = ['MASTER', 'IR CAB', 'RVB MIX', 'RVB DECAY', 'DLY TIME', 'DLY MIX', 'MOD SPEED', 'MOD FX', 'VOLUME', 'BASS', 'MIDDLE', 'TREBLE', 'GAIN', 'TYPE', 'NOISE GATE']
RE = re.compile(r'ch3\(PB1\)=([0-9x,]+)\s+ch\d+=([0-9x,]+)')

class Dev:
    def __init__(self, port):
        self.s = serial.Serial(port, 115200, timeout=0.2)
        try: self.s.dtr = True
        except OSError: pass
        time.sleep(0.3); self.s.reset_input_buffer()
    def knobs(self, ch):
        self.s.write((f'KNOBS {ch}\n').encode()); end = time.time() + 2.0
        while time.time() < end:
            l = self.s.readline().decode(errors='replace').strip()
            m = RE.search(l) if l.startswith('OK KNOBS') else None
            if m:
                v = [None if t == 'x' else int(t) for t in (m.group(1) + ',' + m.group(2)).split(',')]
                if len(v) == 16: return v
            elif l.startswith('ERR'): sys.exit('firmware: ' + l)
        return None

def key():
    """Non-blocking line from stdin: returns the stripped line, '' if none yet, None on EOF."""
    r, _, _ = select.select([sys.stdin], [], [], 0)
    if not r: return ''
    l = sys.stdin.readline()
    return None if l == '' else l.strip().lower()

def read(dev, ch):
    for _ in range(5):
        v = dev.knobs(ch)
        if v: return v
    sys.exit('no KNOBS reply (is the new firmware running? is the port free?)')

def median_baseline(dev, ch, n=5):
    rows = [read(dev, ch) for _ in range(n)]
    return [(int(statistics.median(x for x in (r[i] for r in rows) if x is not None)) if any(r[i] is not None for r in rows) else None) for i in range(16)]

def settle(dev, ch, secs=4.0):
    """wait until two consecutive reads differ by < 25 in every slot; return a median baseline"""
    end = time.time() + secs; prev = read(dev, ch)
    while time.time() < end:
        cur = read(dev, ch)
        if all(a is None or b is None or abs(a - b) < 25 for a, b in zip(prev, cur)): break
        prev = cur
    return median_baseline(dev, ch, 3)

def save(d):
    os.makedirs(os.path.dirname(JSON), exist_ok=True); json.dump(d, open(JSON, 'w'), indent=1)

def write_header(d, path):
    slot = [-1] * 15
    for name, v in d['map'].items(): slot[KNOBS.index(name)] = v['slot']
    inv = [-1] * 16
    for k, s in enumerate(slot):
        if s >= 0: inv[s] = k
    dup = [s for s in set(slot) if s >= 0 and slot.count(s) > 1]
    names = ', '.join(json.dumps(n) for n in KNOBS)
    txt = ['// GENERATED by tools/knob_sweep.py (%s) -- observed by a human turning each knob on the real pedal; -1 = not mapped.' % datetime.date.today().isoformat(),
           '// Raw slot index of the KNOBS command: 0..7 = SARADC ch3 (PB1) at mux address 0..7, 8..15 = second mux (ch8) at address 0..7.',
           '#pragma once', '#include <stdint.h>', 'namespace tg {',
           'constexpr const char* kKnobName[15] = {' + names + '};',
           'constexpr int8_t kKnobSlot[15] = {' + ','.join(map(str, slot)) + '};   // knob (LED order MASTER..NOISE GATE) -> KNOBS slot',
           'constexpr int8_t kSlotKnob[16] = {' + ','.join(map(str, inv)) + '};   // KNOBS slot -> knob index, -1 = none/unknown',
           '}  // namespace tg', '']
    if os.path.exists(path): open(path + '.bak', 'w').write(open(path).read())
    open(path, 'w').write('\n'.join(txt)); print(f'\nWrote {path}')
    if dup: print('  WARNING: slots used by more than one knob:', dup)
    unm = [KNOBS[i] for i, s in enumerate(slot) if s < 0]
    if unm: print('  not mapped:', ', '.join(unm))
    free = [i for i in range(16) if inv[i] < 0]
    print('  slots without a knob:', free)

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--port', default='/dev/ttyACM0'); ap.add_argument('--threshold', type=int, default=200); ap.add_argument('--ch', type=int, default=8, help='SARADC channel of the 2nd mux (default 8)')
    ap.add_argument('--resume', action='store_true'); ap.add_argument('--json', default=JSON); ap.add_argument('--header', default=HDR)
    a = ap.parse_args(); globals()['JSON'] = a.json
    try: dev = Dev(a.port)
    except Exception as e: sys.exit(f'cannot open {a.port}: {e}  (is PulseDeck or another program using it?)')
    d = {'threshold': a.threshold, 'ch': a.ch, 'map': {}, 'skipped': []}
    if a.resume:
        try: d = json.load(open(JSON)); d.setdefault('skipped', [])
        except Exception: pass
    print('Deixe TODOS os knobs parados. Capturando linha de base...')
    base = median_baseline(dev, a.ch, 5); print('base :', ' '.join('x' if v is None else str(v) for v in base))
    i = 0
    while i < len(KNOBS):
        name = KNOBS[i]
        if name in d['map'] or name in d['skipped']: i += 1; continue
        print(f'\n[{i + 1:2d}/15] Gire o knob  {name}  (um bom pedaço, nos dois sentidos se quiser).   s=pular  b=voltar  r=nova base  q=sair')
        lo = {}; hi = {}; found = None; assigned = {v['slot'] for v in d['map'].values()}
        while found is None:
            k = key()
            if k is None: k = 'q'
            if k == 'q': save(d); write_header(d, a.header); return 0
            if k == 's': d['skipped'].append(name); save(d); print('  pulado'); break
            if k == 'r': base = median_baseline(dev, a.ch, 5); print('  nova base'); continue
            if k == 'b':
                if i == 0: print('  já é o primeiro'); continue
                i -= 1; d['map'].pop(KNOBS[i], None)
                if KNOBS[i] in d['skipped']: d['skipped'].remove(KNOBS[i])
                save(d); found = 'back'; break
            cur = dev.knobs(a.ch)
            if cur is None: continue
            best = None
            for s in range(16):
                if s in assigned or cur[s] is None or base[s] is None: continue
                lo[s] = min(lo.get(s, cur[s]), cur[s]); hi[s] = max(hi.get(s, cur[s]), cur[s])
                dlt = abs(cur[s] - base[s])
                if dlt > a.threshold and (best is None or dlt > best[1]): best = (s, dlt, cur[s])
            if best:
                s, dlt, v = best
                d['map'][name] = {'slot': s, 'delta': dlt, 'from': base[s], 'to': v}; save(d); found = s
                print(f'  -> {name}: slot {s}  (de {base[s]} para {v}, variação {dlt}). Pare de girar...')
        if found == 'back': continue
        if isinstance(found, int):
            base = settle(dev, a.ch); print('  nova base:', ' '.join('x' if v is None else str(v) for v in base))
        i += 1
    save(d); write_header(d, a.header)
    print('\nResumo:'); [print(f'  {n:12s} -> slot {d["map"][n]["slot"]}') for n in KNOBS if n in d['map']]
    return 0
if __name__ == '__main__': sys.exit(main())
