#!/usr/bin/env python3 -I
"""Generates src/eq_tables.h: biquad coefficients (Q14, normalised by a0) for the open amp tone stack, from the public RBJ
'Audio EQ Cookbook' formulas (Robert Bristow-Johnson, public domain). fs = 48000. Clean room: formulas only, no vendor data.
  low shelf  120 Hz   S=0.8   -12..+12 dB in 2 dB steps (13 entries)
  peaking    800 Hz   Q=0.7   same grid
  high shelf 3200 Hz  S=0.8   same grid
  cab        low-pass 5200 Hz Q=0.6 (one fixed biquad: a 'speaker-ish' roll-off, NOT an impulse response)
  kCabs      8 speaker-cabinet voicings, each = high-pass + low-pass + 2 peaking biquads. They are OUR voicings from typical public
             descriptions of cabinet frequency response (low cut, mid shape, top roll-off); NOT measured from, or copied from, any
             real cabinet, IR library or product.
  kGeq       band 0 = low shelf at 100 Hz (the '50 Hz' fader), bands 1..5 = peaking at 125, 315, 800, 2000, 5000 Hz (Q=1.2); -12..+12 dB in 2 dB steps"""
import math, sys, os
FS = 48000.0
def norm(b0, b1, b2, a0, a1, a2): return [round(v / a0 * 16384) for v in (b0, b1, b2, a1, a2)]
def shelf(kind, f0, S, dB):
    A = 10 ** (dB / 40); w = 2 * math.pi * f0 / FS; cw, sw = math.cos(w), math.sin(w)
    al = sw / 2 * math.sqrt((A + 1 / A) * (1 / S - 1) + 2); t = 2 * math.sqrt(A) * al
    if kind == 'lo':
        return norm(A * ((A + 1) - (A - 1) * cw + t), 2 * A * ((A - 1) - (A + 1) * cw), A * ((A + 1) - (A - 1) * cw - t),
                    (A + 1) + (A - 1) * cw + t, -2 * ((A - 1) + (A + 1) * cw), (A + 1) + (A - 1) * cw - t)
    return norm(A * ((A + 1) + (A - 1) * cw + t), -2 * A * ((A - 1) + (A + 1) * cw), A * ((A + 1) + (A - 1) * cw - t),
                (A + 1) - (A - 1) * cw + t, 2 * ((A - 1) - (A + 1) * cw), (A + 1) - (A - 1) * cw - t)
def peak(f0, Q, dB):
    A = 10 ** (dB / 40); w = 2 * math.pi * f0 / FS; cw, sw = math.cos(w), math.sin(w); al = sw / (2 * Q)
    return norm(1 + al * A, -2 * cw, 1 - al * A, 1 + al / A, -2 * cw, 1 - al / A)
def lowpass(f0, Q):
    w = 2 * math.pi * f0 / FS; cw, sw = math.cos(w), math.sin(w); al = sw / (2 * Q)
    return norm((1 - cw) / 2, 1 - cw, (1 - cw) / 2, 1 + al, -2 * cw, 1 - al)
grid = range(-12, 13, 2)
out = ['// GENERATED by tools/gen_eq_tables.py (RBJ cookbook formulas, fs 48 kHz). Do not edit. Coefficients Q14: {b0, b1, b2, a1, a2}, index = (dB + 12) / 2.',
       '#pragma once', '#include <stdint.h>', 'namespace tg {', 'constexpr int kEqSteps = 13;']
for name, fn in (('kEqLow', lambda g: shelf('lo', 120, 0.8, g)), ('kEqMid', lambda g: peak(800, 0.7, g)), ('kEqHigh', lambda g: shelf('hi', 3200, 0.8, g))):
    out.append(f'constexpr int32_t {name}[kEqSteps][5] = {{')
    out += ['  {' + ', '.join(map(str, fn(g))) + '},' for g in grid]
    out.append('};')
out.append('constexpr int32_t kCabLp[5] = {' + ', '.join(map(str, lowpass(5200, 0.6))) + '};')
def highpass(f0, Q):
    w = 2 * math.pi * f0 / FS; cw, sw = math.cos(w), math.sin(w); al = sw / (2 * Q)
    c = norm((1 + cw) / 2, -(1 + cw), (1 + cw) / 2, 1 + al, -2 * cw, 1 - al)
    c[1] = -(c[0] + c[2])   # keep the zero exactly at DC: with Q14 rounding a low corner would otherwise leak (error / A(1) ~ 50 %)
    return c
# name, hp, lp (f, Q), peak A (f, Q, dB), peak B (f, Q, dB)
CABS = [("1x12 Clean", 90, (6500, .7), (2200, 1.2, 3), (500, .8, -2)), ("2x12 Brit", 80, (5200, .7), (1800, 1.0, 4), (300, .7, 2)),
        ("4x12 Modern", 75, (4800, .9), (3000, 1.4, 3), (160, .8, 3)), ("1x10 Open", 110, (7200, .7), (3500, 1.0, 2), (800, .8, 2)),
        ("4x12 Vintage", 85, (4200, .8), (2000, 1.6, 4), (700, .9, -3)), ("Bright Combo", 100, (8000, .7), (4500, 1.2, 4), (250, .8, -2)),
        ("Dark Cab", 70, (3500, .7), (1200, 1.0, 2), (200, .8, 3)), ("Studio", 60, (8000, .7), (3000, 1.0, 1), (400, .8, -1))]
out.append('constexpr int kCabCount = 8;   // ir_slot 1..8 -> kCabs[slot-1]; slot 0 = off')
out.append('constexpr int32_t kCabs[kCabCount][4][5] = {')
for nm, hp, lp, a, b in CABS:
    rows = [highpass(hp, .7), lowpass(*lp), peak(a[0], a[1], a[2]), peak(b[0], b[1], b[2])]
    out.append('  {' + ', '.join('{' + ', '.join(map(str, r)) + '}' for r in rows) + '},   // ' + nm)
out.append('};')
out.append('constexpr int32_t kGeq[6][kEqSteps][5] = {')
out.append('  {' + ', '.join('{' + ', '.join(map(str, shelf('lo', 100, 0.8, g))) + '}' for g in grid) + '},   // band 0 ("50 Hz"): a low shelf at 100 Hz -- a 50 Hz peak is too sharp for Q14 coefficients')
for f in (125, 315, 800, 2000, 5000):
    out.append('  {' + ', '.join('{' + ', '.join(map(str, peak(f, 1.2, g))) + '}' for g in grid) + '},')
out.append('};')
out.append('}  // namespace tg')
open(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src/eq_tables.h'), 'w').write('\n'.join(out) + '\n')
print('ok')
