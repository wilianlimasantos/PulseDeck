#!/usr/bin/env python3 -I
"""Generates tests/a2l_ref.h: the A2L1 blobs of PulseDeck's fixture captures (crates/pulsedeck-core/tests/fixtures/{a,b}.ref.a2l, produced by PulseDeck's own converter), a test input and the
float64 output of the SAME network computed here straight from a.nam (plain WaveNet forward pass, as in PulseDeck's a2l.rs::measure).
The firmware's fixed-point player (src/a2l.h) must reproduce that output (tests/test_a2l.cpp)."""
import json, math, os, struct, sys
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fx = os.path.join(here, '..', 'crates', 'pulsedeck-core', 'tests', 'fixtures')
out = ['// GENERATED by tools/gen_a2l_ref.py. Do not edit.', '#pragma once', '#include <stdint.h>']
for tag in ('a', 'b'):
    d = json.load(open(os.path.join(fx, tag + '.nam'))); blob = open(os.path.join(fx, tag + '.ref.a2l'), 'rb').read()
    l = d['config']['layers'][0]; C = 3; ks = l['kernel_sizes']; ds = l['dilations']; hk = l['head']['kernel_size']
    w = [struct.unpack('f', struct.pack('f', v))[0] for v in d['weights']]; o = 0
    def take(n):
        global o
        s = w[o:o + n]; o += n; return s
    rech = take(C); layers = []
    for K, dil in zip(ks, ds):
        layers.append(dict(K=K, d=dil, cw=take(C * C * K), cb=take(C), mw=take(C), lw=take(C * C), lb=take(C), slope=l['activation'].get('negative_slope', 0.01)))
    hw = take(C * hk); hb = take(1)[0]; hs = d['config'].get('head_scale', 1.0)
    N = 3000 if tag == 'a' else 1500
    seed = 12345
    def rnd():
        global seed
        seed = (seed * 1664525 + 1013904223) & 0xFFFFFFFF; return (seed >> 8) / 16777216.0 * 2 - 1
    x = [int(round((0.25 * math.sin(2 * math.pi * 196 * i / 48000) + 0.12 * math.sin(2 * math.pi * 1310 * i / 48000) + 0.05 * rnd()) * 8388607)) for i in range(N)]
    xin = [v / 8388608.0 for v in x]
    hist = [[[0.0] * ((L['K'] - 1) * L['d'] + 1) for _ in range(C)] for L in layers]; pos = [0] * len(layers)
    hh = [[0.0] * hk for _ in range(C)]; hp = 0; y = []
    for t in range(N):
        cur = [rech[c] * xin[t] for c in range(C)]; head = [0.0] * C
        for i, L in enumerate(layers):
            K, dil = L['K'], L['d']; ln = (K - 1) * dil + 1; p = pos[i]
            for c in range(C): hist[i][c][p] = cur[c]
            a = []
            for co in range(C):
                z = L['cb'][co]
                for ci in range(C):
                    for k in range(K): z += L['cw'][(co * C + ci) * K + k] * hist[i][ci][(p - (K - 1 - k) * dil) % ln]
                z += L['mw'][co] * xin[t]; a.append(z if z >= 0 else L['slope'] * z)
            cur = [cur[co] + sum(L['lw'][co * C + ci] * a[ci] for ci in range(C)) + L['lb'][co] for co in range(C)]
            head = [head[c] + a[c] for c in range(C)]; pos[i] = (p + 1) % ln
        for c in range(C): hh[c][hp] = head[c]
        v = hb
        for c in range(C):
            for k in range(hk): v += hw[c * hk + k] * hh[c][(hp - (hk - 1 - k)) % hk]
        hp = (hp + 1) % hk; y.append(v * hs)
    out.append(f'static const unsigned kA2l_{tag}_len = {len(blob)}, kA2l_{tag}_n = {N};')
    out.append(f'static const uint8_t kA2l_{tag}_blob[] = {{' + ','.join(map(str, blob)) + '};')
    out.append(f'static const int32_t kA2l_{tag}_in[] = {{' + ','.join(map(str, x)) + '};')
    out.append(f'static const double kA2l_{tag}_out[] = {{' + ','.join(f'{v:.9g}' for v in y) + '};')
    print(tag, 'layers', len(layers), 'rms out', (sum(v * v for v in y) / N) ** .5)
open(os.path.join(here, 'tests', 'a2l_ref.h'), 'w').write('\n'.join(out) + '\n')
